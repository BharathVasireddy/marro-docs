// Text helpers

/** Escapes text for MDX: braces and angle brackets outside `code`, pipes everywhere in tables. */
function mdx(text = '', { table = false } = {}) {
    const parts = String(text).split(/(`[^`]*`)/g).map((part) => {
        if (part.startsWith('`') && part.endsWith('`') && part.length > 1) return table ? part.replaceAll('|', '\\|') : part;
        let out = part.replace(/[{}<>]/g, (char) => `&#${char.charCodeAt(0)};`);
        if (table) out = out.replaceAll('|', '\\|');
        return out;
    });
    const joined = parts.join('');
    return table ? joined.replace(/\s*\n+\s*/g, ' ') : joined;
}

function table(headers, rows) {
    if (rows.length === 0) return '';
    return [
        `| ${headers.join(' | ')} |`,
        `| ${headers.map(() => '---').join(' | ')} |`,
        ...rows.map((row) => `| ${row.map((cell) => mdx(cell, { table: true }) || ' ').join(' | ')} |`),
    ].join('\n');
}

function fence(lang, code, title = '') {
    const ticks = code.includes('```') ? '````' : '```';
    return `${ticks}${lang}${title ? ` ${title}` : ''}\n${code}\n${ticks}`;
}

function slug(text) {
    return String(text).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function shellQuote(text) {
    return `'${text.replaceAll("'", `'\\''`)}'`;
}

// ---------------------------------------------------------------------------------------------
// Reading the document

function operations(spec) {
    const list = [];
    for (const [path, item] of Object.entries(spec.paths)) {
        for (const method of METHODS) {
            const op = item[method];
            if (!op) continue;
            const tag = op.tags?.[0] ?? 'Other';
            const id = op.operationId ?? slug(`${method} ${path}`);
            list.push({ path, method, op, tag, id, page: `${REFERENCE_DIR}/${slug(tag)}/${id}` });
        }
    }
    return list;
}

function resolve(schema, root) {
    if (!schema?.$ref) return schema ?? {};
    const [, kind, name] = schema.$ref.match(/^#\/(\$defs|components\/schemas)\/(.+)$/) ?? [];
    const target = kind === '$defs' ? root?.$defs?.[name] : kind ? globalThis.SPEC.components?.schemas?.[name] : undefined;
    return target ? { ...target, ...Object.fromEntries(Object.entries(schema).filter(([key]) => key !== '$ref')) } : schema;
}

/** A short readable type, like "string (email)", "integer", "object", "array of string". */
function typeOf(input, root) {
    const schema = resolve(input, root);
    const variants = schema.anyOf ?? schema.oneOf;
    if (variants) {
        const types = variants.filter((variant) => variant.type !== 'null').map((variant) => typeOf(variant, root));
        return types.length < variants.length ? `${types.join(' or ')} or null` : types.join(' or ');
    }
    if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(', ');
    const type = Array.isArray(schema.type) ? schema.type.filter((item) => item !== 'null').join(' or ') : schema.type;
    if (type === 'array') return `array of ${schema.items ? typeOf(schema.items, root) : 'any'}`;
    if (type === 'string' && schema.format) return `string (${schema.format})`;
    return type ?? 'object';
}

/** Error responses, read from descriptions in the form "CODE: when". */
function errorResponses(op) {
    return Object.entries(op.responses ?? {}).flatMap(([status, response]) => {
        const match = response.description?.match(/^([A-Z][A-Z0-9_]+): ([\s\S]*)$/);
        return match ? [{ status, code: match[1], when: match[2].trim() }] : [];
    });
}

/** Scopes as the document states them: per operation (security) and named in the scheme. */
function scopes(spec, ops) {
    const scheme = Object.values(spec.components?.securitySchemes ?? {})[0] ?? {};
    const extension = scheme['x-scopes'];
    const labels = new Map();
    for (const match of (scheme.description ?? '').matchAll(/`([a-z0-9_.]+)` \(([^)]+)\)/g)) labels.set(match[1], match[2]);
    const byScope = new Map();
    for (const item of ops) {
        for (const requirement of item.op.security ?? spec.security ?? []) {
            for (const list of Object.values(requirement)) {
                for (const scope of list) {
                    if (!byScope.has(scope)) byScope.set(scope, []);
                    byScope.get(scope).push(item);
                }
            }
        }
    }
    const ids = [...new Set([...labels.keys(), ...byScope.keys(), ...Object.keys(extension ?? {})])];
    return ids.map((id) => ({
        id,
        label: extension?.[id]?.label ?? labels.get(id) ?? '',
        description: extension?.[id]?.description ?? '',
        module: extension?.[id]?.module ?? '',
        operations: byScope.get(id) ?? [],
    }));
}

function link(item) {
    return `[${item.op.summary ?? `${item.method.toUpperCase()} ${item.path}`}](/${item.page})`;
}

