#!/usr/bin/env node
/**
 * Refreshes everything in these docs that comes from the API:
 *
 *   1. downloads the OpenAPI document into openapi.json,
 *   2. writes the MDX snippets in snippets/generated/ that the guide pages include,
 *   3. writes one page per endpoint in api-reference/ and the "API reference" tab in docs.json.
 *
 * Run it with `npm run update`. It is idempotent: running it twice on the same document changes
 * nothing. Set OPENAPI_URL to read another server, or OPENAPI_OFFLINE=1 to regenerate from the
 * openapi.json already in the repo.
 *
 * Facts the document does not contain are not written here by hand. Optional extensions the CRM
 * can add to its document (shapes in README.md) are used when present: x-scopes, x-rate-limits,
 * x-transport-errors, x-filter-operators, x-codeSamples.
 */
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_URL = process.env.OPENAPI_URL ?? 'https://app.marro.si/api/v1/openapi.json';
const SPEC_FILE = join(ROOT, 'openapi.json');
const SNIPPETS = join(ROOT, 'snippets', 'generated');
const REFERENCE_DIR = 'api-reference';
const REFERENCE_TAB = 'API reference';
const HEADER = '{/* Generated by scripts/update.mjs from openapi.json. Do not edit; run `npm run update`. */}\n\n';
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

// ---------------------------------------------------------------------------------------------
// Loading

async function loadSpec() {
    if (process.env.OPENAPI_OFFLINE !== '1') {
        const response = await fetch(SPEC_URL, { signal: AbortSignal.timeout(30_000) });
        if (!response.ok) throw new Error(`Could not download ${SPEC_URL}: HTTP ${response.status}`);
        const spec = await response.json();
        if (!spec.openapi || !spec.paths) throw new Error(`${SPEC_URL} is not an OpenAPI document`);
        hoistDefs(spec);
        await writeIfChanged(SPEC_FILE, `${JSON.stringify(spec, null, 2)}\n`);
        return spec;
    }
    const spec = JSON.parse(await readFile(SPEC_FILE, 'utf8'));
    hoistDefs(spec);
    return spec;
}

/**
 * The CRM's document nests `$defs` inside each schema and points at them with `#/$defs/Name`,
 * which OpenAPI tools resolve from the document root and so cannot find. This moves every nested
 * definition into `components.schemas` and points the references there. Identical definitions
 * with the same name are shared; a different one with a taken name gets a numbered name.
 */
function hoistDefs(spec) {
    spec.components ??= {};
    spec.components.schemas ??= {};
    const schemas = spec.components.schemas;
    const queue = [spec.paths, ...Object.values(schemas)];
    while (queue.length > 0) {
        const node = queue.shift();
        if (!node || typeof node !== 'object') continue;
        if (!Array.isArray(node) && node.$defs && typeof node.$defs === 'object') {
            const defs = node.$defs;
            delete node.$defs;
            const names = {};
            for (const [name, definition] of Object.entries(defs)) {
                let target = name;
                for (let index = 2; schemas[target] && !sameRefsAside(schemas[target], definition, defs, name); index += 1) target = `${name}${index}`;
                names[name] = target;
            }
            const rewrite = (value) => {
                if (!value || typeof value !== 'object') return;
                if (Array.isArray(value)) { value.forEach(rewrite); return; }
                const match = typeof value.$ref === 'string' ? value.$ref.match(/^#\/\$defs\/(.+)$/) : null;
                if (match && names[match[1]]) value.$ref = `#/components/schemas/${names[match[1]]}`;
                Object.values(value).forEach(rewrite);
            };
            rewrite(node);
            rewrite(defs);
            for (const [name, definition] of Object.entries(defs)) {
                if (!schemas[names[name]]) {
                    schemas[names[name]] = definition;
                    queue.push(definition);
                }
            }
        }
        for (const value of Array.isArray(node) ? node : Object.values(node)) if (value && typeof value === 'object') queue.push(value);
    }
}

/** Whether an already-hoisted schema is the same definition (compared with its refs not yet rewritten). */
function sameRefsAside(existing, definition) {
    const plain = (value) => JSON.stringify(value, (key, item) => (key === '$ref' && typeof item === 'string' ? item.replace(/^#\/(\$defs|components\/schemas)\/([A-Za-z_]+?)\d*$/, '$2') : item));
    return plain(existing) === plain(definition);
}

const written = new Set();

async function writeIfChanged(file, content) {
    written.add(file);
    let current = null;
    try { current = await readFile(file, 'utf8'); } catch { /* new file */ }
    if (current === content) return;
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, content);
    console.log(`wrote ${file.slice(ROOT.length + 1)}`);
}

